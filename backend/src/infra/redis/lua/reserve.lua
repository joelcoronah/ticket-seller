--[[
  reserve.lua — atomic seat hold. The ONLY code path where a seat leaves `available`.

  Redis runs this script single-threaded and atomically, so 5,000 concurrent
  calls are serialized: a seat can be popped from `available` exactly once.

  KEYS[1] ev:{E}:available   SET   seats that can be sold right now
  KEYS[2] ev:{E}:holds       ZSET  seat -> hold expiresAt (ms)
  KEYS[3] ev:{E}:holdmeta    HASH  seat -> "holdId|userId"
  KEYS[4] ev:{E}:user:{U}    STR   "holdId|seat" (PX ttl) -> max 1 active hold per user
  KEYS[5] ev:{E}:req:{R}     STR   cached JSON result (idempotency: Kafka is at-least-once)
  KEYS[6] ev:{E}:queue:done  STR   highest queue position processed (UX only)

  ARGV[1] seatId ('' = best available)
  ARGV[2] userId
  ARGV[3] holdId (uuid generated by the caller)
  ARGV[4] hold TTL in ms
  ARGV[5] result cache TTL in seconds
  ARGV[6] queue position of this request
  ARGV[7] max expired holds to reclaim lazily in this call
]]

-- 1. Idempotency: a redelivered message returns the original outcome.
local cached = redis.call('GET', KEYS[5])
if cached then return cached end

-- Server clock, never the client's: all TTL math uses one time source.
local t = redis.call('TIME')
local now = tonumber(t[1]) * 1000 + math.floor(tonumber(t[2]) / 1000)

-- 2. Lazy reclaim: expired holds go back to `available` even if the reaper is down.
local expired = redis.call('ZRANGEBYSCORE', KEYS[2], '-inf', now, 'LIMIT', 0, tonumber(ARGV[7]))
for _, s in ipairs(expired) do
  redis.call('ZREM', KEYS[2], s)
  redis.call('HDEL', KEYS[3], s)
  redis.call('SADD', KEYS[1], s)
end

local function finish(result)
  redis.call('SET', KEYS[5], result, 'EX', tonumber(ARGV[5]))
  local done = tonumber(redis.call('GET', KEYS[6]) or '0')
  if tonumber(ARGV[6]) > done then redis.call('SET', KEYS[6], ARGV[6]) end
  return result
end

-- 3. One active hold per user per event.
local existing = redis.call('GET', KEYS[4])
if existing then
  local sep = string.find(existing, '|', 1, true)
  return finish(cjson.encode({
    status = 'USER_HAS_HOLD',
    holdId = string.sub(existing, 1, sep - 1),
    seatId = string.sub(existing, sep + 1),
  }))
end

-- 4. Take the seat. SPOP/SREM are the atomic "decrement" of stock.
local seat = ARGV[1]
if seat == '' then
  seat = redis.call('SPOP', KEYS[1])
  if not seat then return finish(cjson.encode({ status = 'SOLD_OUT' })) end
elseif redis.call('SREM', KEYS[1], seat) == 0 then
  return finish(cjson.encode({ status = 'SEAT_UNAVAILABLE', seatId = seat }))
end

-- 5. Record the hold with its expiry.
local ttl = tonumber(ARGV[4])
local expiresAt = now + ttl
redis.call('ZADD', KEYS[2], expiresAt, seat)
redis.call('HSET', KEYS[3], seat, ARGV[3] .. '|' .. ARGV[2])
redis.call('SET', KEYS[4], ARGV[3] .. '|' .. seat, 'PX', ttl)

return finish(cjson.encode({
  status = 'HELD',
  holdId = ARGV[3],
  seatId = seat,
  expiresAt = expiresAt,
}))
